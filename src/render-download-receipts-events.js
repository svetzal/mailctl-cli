import {
  doclingFailed,
  downloadedPdf,
  downloadSummary,
  dryRunJson,
  dryRunMetadata,
  dryRunPdf,
  emptyExtractionSkipped,
  llmDisabled,
  llmEnabled,
  llmExtractionFailed,
  llmNotConfigured,
  mailboxCandidates,
  mailboxFetchError,
  mailboxSearchStart,
  processError,
  reprocessDoclingFailed,
  reprocessDryRun,
  reprocessDryRunBody,
  reprocessError,
  reprocessNoData,
  reprocessReclassified,
  reprocessSkipped,
  reprocessStart,
  reprocessSummary,
  reprocessUpdated,
  reprocessUsingBody,
  searchAccount,
  searchTermError,
  skipDuplicate,
  skipExistingInvoice,
  skipLowConfidence,
  skipNonInvoice,
  subjectExclusions,
  uniqueReceipts,
  usingPdfContent,
  vendorFilterApplied,
  wroteMetadata,
} from "./download-receipts-event-factories.js";
import { formatKB } from "./format-bytes.js";
import { createEventRenderer } from "./render-shared-events.js";

/** @type {(event: object) => string | null} */
export const renderDownloadReceiptsEvent = createEventRenderer({
  [llmEnabled.type]: () => "Using LLM (gpt-5-mini) for receipt data extraction",
  [llmDisabled.type]: () => "OPENAI_API_KEY not set — using pattern-based extraction",
  [llmNotConfigured.type]: (e) => `   Warning: Could not initialize LLM broker: ${e.error.message}`,
  [searchAccount.type]: (e) => `\nSearching ${e.name} (${e.user})...`,
  [mailboxSearchStart.type]: (e) => `   ${e.mailbox} (${e.messageCount} messages)...`,
  [mailboxCandidates.type]: (e) => `      ${e.count} candidates`,
  [mailboxFetchError.type]: (e) => `      Fetch failed: ${e.error.message}`,
  [searchTermError.type]: (e) => `   Search error in ${e.mailbox}: ${e.error.message}`,
  [vendorFilterApplied.type]: (e) =>
    `   Filtered to ${e.matchCount} of ${e.matchCount + e.excludedCount} messages matching vendor "${e.vendor}"`,
  [subjectExclusions.type]: (e) => `   Excluded ${e.count} non-invoice subjects`,
  [uniqueReceipts.type]: (e) => `   ${e.count} unique receipt emails`,
  [usingPdfContent.type]: (e) => `      Using PDF content for extraction (UID ${e.uid})`,
  [doclingFailed.type]: (e) => `      Docling failed for UID ${e.uid}: ${e.error.message}`,
  [llmExtractionFailed.type]: (e) => `   LLM extraction failed: ${e.error.message}`,
  [skipNonInvoice.type]: (e) =>
    `   Skipping ${e.vendor} — classified as non-invoice (confidence: ${(e.confidence || 0).toFixed(2)})`,
  [skipLowConfidence.type]: (e) => `   Skipping ${e.vendor} — low confidence ${e.confidence.toFixed(2)}`,
  [skipExistingInvoice.type]: (e) => `   Skipping ${e.vendor} ${e.invoiceNumber} — already exists`,
  [emptyExtractionSkipped.type]: (e) =>
    `   Skipping ${e.vendor || e.sourceEmail} — empty extraction (no amount, no invoice number, no PDF)`,
  [skipDuplicate.type]: (e) => `   Skipping ${e.label} — duplicate content`,
  [dryRunPdf.type]: (e) => `   [DRY RUN] ${e.filename}`,
  [dryRunJson.type]: (e) => `   [DRY RUN] ${e.filename}`,
  [downloadedPdf.type]: (e) => `   Downloaded: ${e.filename} (${formatKB(e.size)})`,
  [dryRunMetadata.type]: (e) => `   [DRY RUN] ${e.filename} (no PDF)`,
  [wroteMetadata.type]: (e) => `   Wrote metadata: ${e.filename} (no PDF)`,
  [processError.type]: (e) => `   Error processing UID ${e.uid}: ${e.error.message}`,
  [downloadSummary.type]: (e) => {
    const s = e.stats;
    return [
      `\n=== Download Complete ===`,
      `Found:       ${s.found}`,
      `Downloaded:  ${s.downloaded}`,
      `No PDF:      ${s.noPdf}`,
      `Skipped:     ${s.skipped} (non-invoice or low confidence)`,
      `Empty:       ${s.skippedEmpty ?? 0} (no amount, no invoice number, no PDF)`,
      `Duplicates:  ${s.alreadyHave}`,
      `Errors:      ${s.errors}`,
    ].join("\n");
  },
  [reprocessStart.type]: (e) => `Reprocessing receipts in ${e.outputDir}...`,
  [reprocessDryRun.type]: (e) => `  [DRY RUN] ${e.filename} — would reprocess`,
  [reprocessDoclingFailed.type]: (e) => `  ❌ ${e.filename} — docling conversion failed`,
  [reprocessDryRunBody.type]: (e) => `  [DRY RUN] ${e.filename} — would reprocess (body snippet)`,
  [reprocessUsingBody.type]: (e) => `      Using stored body snippet for extraction (${e.filename})`,
  [reprocessSkipped.type]: (e) => `  ⏭️  ${e.filename} — ${e.reason}, skipped`,
  [reprocessNoData.type]: (e) => `  ❌ ${e.filename} — LLM extraction returned no data`,
  [reprocessReclassified.type]: (e) => `  🗑️  ${e.filename} — reclassified as non-invoice, removing`,
  [reprocessUpdated.type]: (e) => `  ✅ ${e.filename} — updated metadata`,
  [reprocessError.type]: (e) => `  ❌ ${e.filename} — extraction failed: ${e.error.message}`,
  [reprocessSummary.type]: (e) =>
    `\nReprocessed: ${e.reprocessed}, Skipped: ${e.skipped}, Reclassified: ${e.reclassified}, Errors: ${e.errors}`,
});
